// 按 category 分组排序
const CATEGORY_ORDER = ['独立新能源品牌', '海外新能源品牌', '传统自主品牌']

exports.main = async (event) => {
  const { action } = event

  switch (action) {
    case 'brands': {
      // 返回所有品牌，按 category 分组
      const grouped = {}
      CATEGORY_ORDER.forEach(cat => { grouped[cat] = [] })
      VEHICLE_CATALOG.forEach(b => {
        const cat = b.category
        if (!grouped[cat]) grouped[cat] = []
        grouped[cat].push(b.brand_name)
      })
      // 品牌列表（带分组）
      const brandOptions = []
      CATEGORY_ORDER.forEach(cat => {
        if (grouped[cat] && grouped[cat].length) {
          brandOptions.push({ category: cat, brands: grouped[cat] })
        }
      })
      return { code: 0, data: brandOptions }
    }

    case 'models': {
      // 根据 brand_name 返回车型列表
      const { brandName } = event
      if (!brandName) return { code: -1, msg: '缺少brandName' }
      const brandItem = VEHICLE_CATALOG.find(b => b.brand_name === brandName)
      if (!brandItem) return { code: -1, msg: '品牌不存在' }
      const models = brandItem.brand_list.map(m => ({
        model_name: m.model_name,
        energy_type: m.energy_type,
        vehicle_type: m.vehicle_type,
        price_range: m.price_range,
      }))
      return { code: 0, data: models }
    }

    case 'styles': {
      // 根据 brandName + modelName 返回款式列表
      const { brandName, modelName } = event
      if (!brandName || !modelName) return { code: -1, msg: '缺少brandName或modelName' }
      const brandItem = VEHICLE_CATALOG.find(b => b.brand_name === brandName)
      if (!brandItem) return { code: -1, msg: '品牌不存在' }
      const modelItem = brandItem.brand_list.find(m => m.model_name === modelName)
      if (!modelItem) return { code: -1, msg: '车型不存在' }
      const styles = modelItem.car_style_list.map(s => ({
        style_name: s.style_name,
        capacity: s.capacity,
      }))
      return { code: 0, data: styles }
    }

    case 'fullCatalog': {
      // 返回完整目录（供缓存用）
      return { code: 0, data: VEHICLE_CATALOG }
    }

    default:
      return { code: -1, msg: '未知action' }
  }
}